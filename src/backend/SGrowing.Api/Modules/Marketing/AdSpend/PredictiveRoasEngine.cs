using System.Collections.Concurrent;

namespace SGrowing.Api.Modules.Marketing.AdSpend;

/// <summary>
/// Parameters defining the Hill equation curve for marketing ad spend diminishing returns.
/// Formula: Y(x) = (Vmax * x^n) / (K^n + x^n)
/// </summary>
/// <param name="Vmax">Maximum achievable revenue or conversion ceiling (asymptote as spend -> infinity).</param>
/// <param name="K">Half-saturation spend point where Y(K) = Vmax / 2.</param>
/// <param name="HillExponent">Sigmoid steepness exponent n (n > 0). n = 1: hyperbolic; n > 1: sigmoidal S-curve.</param>
public record HillParameters(double Vmax, double K, double HillExponent)
{
    public static HillParameters DefaultMeta => new(Vmax: 50_000.0, K: 6_000.0, HillExponent: 1.8);
    public static HillParameters DefaultGoogle => new(Vmax: 45_000.0, K: 5_000.0, HillExponent: 1.5);
    public static HillParameters DefaultTikTok => new(Vmax: 35_000.0, K: 4_500.0, HillExponent: 2.0);
    public static HillParameters DefaultSnapchat => new(Vmax: 20_000.0, K: 3_000.0, HillExponent: 1.6);
}

/// <summary>
/// Representation of an ordered customer journey touchpoint path for Markov multi-touch attribution.
/// </summary>
/// <param name="Touchpoints">Ordered sequence of marketing channels visited (e.g. ["Meta", "Google", "Email"]).</param>
/// <param name="Converted">Whether the journey resulted in a conversion.</param>
/// <param name="ConversionValue">Total monetary revenue or credit generated by the conversion.</param>
/// <param name="Count">Frequency weight of this identical path (defaults to 1).</param>
public record CustomerJourneyPath(
    IReadOnlyList<string> Touchpoints,
    bool Converted,
    double ConversionValue = 1.0,
    int Count = 1);

/// <summary>
/// Bayesian Beta-Binomial posterior estimation of channel conversion probability.
/// </summary>
public record BayesianConversionPosterior(
    string Channel,
    double PriorAlpha,
    double PriorBeta,
    int ConvertingTouches,
    int NonConvertingTouches,
    double PosteriorAlpha,
    double PosteriorBeta,
    double ExpectedConversionRate,
    double Variance,
    double CredibleIntervalLower,
    double CredibleIntervalUpper);

/// <summary>
/// Result of multi-touch attribution combining Markov chain removal effects and Bayesian posterior probabilities.
/// </summary>
public record MarkovAttributionResult(
    string Channel,
    double RemovalEffect,
    double MarkovAttributionWeight,
    double BayesianConversionProbability,
    double BlendedAttributionWeight,
    double AttributedConversions,
    double AttributedRevenue);

/// <summary>
/// Efficiency classification for ad spend allocation decisions.
/// </summary>
public enum ChannelEfficiencyTier
{
    AggressiveScaleUp,
    ScaleUp,
    Optimal,
    SaturatedReduce,
    UnprofitableKill
}

/// <summary>
/// Comprehensive channel performance snapshot and saturation diagnostics.
/// </summary>
public record ChannelEfficiencyRanking(
    string ChannelId,
    string ChannelName,
    double CurrentSpend,
    double PredictedRevenue,
    double AverageRoas,
    double MarginalRoas,
    double SaturationPercentage,
    double HalfSaturationSpendK,
    ChannelEfficiencyTier Tier,
    string Recommendation);

/// <summary>
/// Core contract for Horizon 49 Autonomous Cross-Channel Predictive ROAS &amp; Diminishing Returns Engine.
/// </summary>
public interface IPredictiveRoasEngine
{
    double EvaluateHillCurve(double spend, HillParameters parameters);
    double CalculateMarginalRoas(double spend, HillParameters parameters);
    double CalculateAverageRoas(double spend, HillParameters parameters);
    double CalculateSaturationPercentage(double spend, HillParameters parameters);
    double CalculateSpendForTargetSaturation(double saturationPercentage, HillParameters parameters);
    double CalculateOptimalHurdleSpend(HillParameters parameters, double targetMarginalRoas = 1.0);
    IReadOnlyList<MarkovAttributionResult> CalculateMarkovBayesianAttribution(
        IReadOnlyList<CustomerJourneyPath> journeys,
        double priorAlpha = 1.0,
        double priorBeta = 1.0);
    IReadOnlyList<ChannelEfficiencyRanking> RankChannelsByEfficiency(
        IReadOnlyList<(string ChannelId, string ChannelName, double CurrentSpend, HillParameters Params)> channels);
}

/// <summary>
/// Implementation of Horizon 49 Autonomous Cross-Channel Predictive ROAS Engine.
/// Formulates non-linear Hill diminishing returns, analytical marginal ROAS derivatives,
/// absorbing Markov chain transition matrices with removal effects, and Bayesian Beta-Binomial posteriors.
/// </summary>
public class PredictiveRoasEngine : IPredictiveRoasEngine
{
    private const string StartState = "(start)";
    private const string ConversionState = "(conversion)";
    private const string DropOffState = "(null)";

    /// <summary>
    /// Evaluates the Hill saturation curve Y(x) = (Vmax * x^n) / (K^n + x^n).
    /// Handles edge cases: x &lt;= 0 returns 0.0; x -> infinity returns Vmax.
    /// </summary>
    public double EvaluateHillCurve(double spend, HillParameters parameters)
    {
        if (double.IsNaN(spend) || spend <= 0.0 || parameters.Vmax <= 0.0 || parameters.K <= 0.0 || parameters.HillExponent <= 0.0)
        {
            return 0.0;
        }

        if (double.IsPositiveInfinity(spend))
        {
            return parameters.Vmax;
        }

        double n = parameters.HillExponent;
        double xn = Math.Pow(spend, n);
        double kn = Math.Pow(parameters.K, n);
        double denominator = kn + xn;

        if (denominator <= 0.0 || double.IsNaN(denominator))
        {
            return 0.0;
        }

        return (parameters.Vmax * xn) / denominator;
    }

    /// <summary>
    /// Calculates the analytical first derivative dY/dx = (Vmax * n * K^n * x^(n - 1)) / (K^n + x^n)^2.
    /// Edge cases: x &lt;= 0 returns 0.0; x -> infinity returns 0.0.
    /// </summary>
    public double CalculateMarginalRoas(double spend, HillParameters parameters)
    {
        if (double.IsNaN(spend) || spend <= 0.0 || double.IsInfinity(spend) ||
            parameters.Vmax <= 0.0 || parameters.K <= 0.0 || parameters.HillExponent <= 0.0)
        {
            return 0.0;
        }

        double n = parameters.HillExponent;
        double kn = Math.Pow(parameters.K, n);
        double xn = Math.Pow(spend, n);
        double xnMinus1 = Math.Pow(spend, n - 1.0);

        double denom = kn + xn;
        double denomSquared = denom * denom;

        if (denomSquared <= 0.0 || double.IsNaN(denomSquared))
        {
            return 0.0;
        }

        return (parameters.Vmax * n * kn * xnMinus1) / denomSquared;
    }

    /// <summary>
    /// Calculates the average ROAS Y(x) / x. Returns 0.0 if spend &lt;= 0.
    /// </summary>
    public double CalculateAverageRoas(double spend, HillParameters parameters)
    {
        if (spend <= 0.0 || double.IsNaN(spend) || double.IsInfinity(spend))
        {
            return 0.0;
        }

        return EvaluateHillCurve(spend, parameters) / spend;
    }

    /// <summary>
    /// Calculates current saturation percentage relative to Vmax: (Y(x) / Vmax) * 100%.
    /// </summary>
    public double CalculateSaturationPercentage(double spend, HillParameters parameters)
    {
        if (spend <= 0.0 || parameters.Vmax <= 0.0)
        {
            return 0.0;
        }

        double revenue = EvaluateHillCurve(spend, parameters);
        return Math.Clamp((revenue / parameters.Vmax) * 100.0, 0.0, 100.0);
    }

    /// <summary>
    /// Solves the inverse Hill function to find the exact spend required to achieve a target saturation percentage S.
    /// Analytical solution: x = K * (S / (100 - S))^(1/n).
    /// </summary>
    public double CalculateSpendForTargetSaturation(double saturationPercentage, HillParameters parameters)
    {
        if (saturationPercentage <= 0.0 || parameters.K <= 0.0 || parameters.HillExponent <= 0.0)
        {
            return 0.0;
        }

        if (saturationPercentage >= 100.0)
        {
            return double.PositiveInfinity;
        }

        double sRatio = saturationPercentage / (100.0 - saturationPercentage);
        double rootExponent = 1.0 / parameters.HillExponent;

        return parameters.K * Math.Pow(sRatio, rootExponent);
    }

    /// <summary>
    /// Finds the optimal ad spend where Marginal ROAS falls to the hurdle rate (e.g. 1.0 break-even),
    /// using closed-form derivation for n = 1 and robust bisection past the inflection point for n != 1.
    /// </summary>
    public double CalculateOptimalHurdleSpend(HillParameters parameters, double targetMarginalRoas = 1.0)
    {
        if (targetMarginalRoas <= 0.0 || parameters.Vmax <= 0.0 || parameters.K <= 0.0 || parameters.HillExponent <= 0.0)
        {
            return 0.0;
        }

        // For n = 1: dY/dx = (Vmax * K) / (K + x)^2 = R => x = sqrt((Vmax * K) / R) - K
        if (Math.Abs(parameters.HillExponent - 1.0) < 1e-6)
        {
            double inside = (parameters.Vmax * parameters.K) / targetMarginalRoas;
            if (inside <= 0.0) return 0.0;
            double xOpt = Math.Sqrt(inside) - parameters.K;
            return Math.Max(0.0, xOpt);
        }

        // For general n, find inflection point where second derivative is 0:
        // x_inflection = K * ((n - 1) / (n + 1))^(1/n) when n > 1
        double xStart = 0.01;
        if (parameters.HillExponent > 1.0)
        {
            double ratio = (parameters.HillExponent - 1.0) / (parameters.HillExponent + 1.0);
            xStart = parameters.K * Math.Pow(ratio, 1.0 / parameters.HillExponent);
        }

        // Bisection search from inflection point up to 20x K
        double low = xStart;
        double high = Math.Max(parameters.K * 20.0, 100_000.0);

        // If even at inflection point marginal ROAS is below target, cannot achieve target
        if (CalculateMarginalRoas(low, parameters) < targetMarginalRoas)
        {
            return 0.0;
        }

        for (int iter = 0; iter < 64; iter++)
        {
            double mid = (low + high) / 2.0;
            double m = CalculateMarginalRoas(mid, parameters);

            if (Math.Abs(m - targetMarginalRoas) < 1e-5 || (high - low) < 1e-4)
            {
                return mid;
            }

            if (m > targetMarginalRoas)
            {
                low = mid;
            }
            else
            {
                high = mid;
            }
        }

        return (low + high) / 2.0;
    }

    /// <summary>
    /// Executes Markov Chain multi-touch attribution with removal effects, blended with
    /// Bayesian Beta-Binomial posterior conversion probabilities.
    /// </summary>
    public IReadOnlyList<MarkovAttributionResult> CalculateMarkovBayesianAttribution(
        IReadOnlyList<CustomerJourneyPath> journeys,
        double priorAlpha = 1.0,
        double priorBeta = 1.0)
    {
        if (journeys.Count == 0)
        {
            return [];
        }

        // 1. Identify distinct marketing channels
        var distinctChannels = journeys
            .SelectMany(j => j.Touchpoints)
            .Where(t => !string.IsNullOrWhiteSpace(t))
            .Distinct(StringComparer.OrdinalIgnoreCase)
            .OrderBy(c => c, StringComparer.OrdinalIgnoreCase)
            .ToList();

        if (distinctChannels.Count == 0)
        {
            return [];
        }

        // 2. Build Markov transition counts
        var transitionCounts = new Dictionary<(string From, string To), double>();

        double totalConversions = 0.0;
        double totalRevenue = 0.0;

        // Track touches for Bayesian modeling
        var channelConvertingTouches = distinctChannels.ToDictionary(c => c, _ => 0, StringComparer.OrdinalIgnoreCase);
        var channelNonConvertingTouches = distinctChannels.ToDictionary(c => c, _ => 0, StringComparer.OrdinalIgnoreCase);

        foreach (var journey in journeys)
        {
            int count = Math.Max(1, journey.Count);
            if (journey.Converted)
            {
                totalConversions += count;
                totalRevenue += journey.ConversionValue * count;
            }

            var cleanTouches = journey.Touchpoints
                .Where(t => !string.IsNullOrWhiteSpace(t))
                .ToList();

            // Track distinct channel involvement in journey for Beta-Binomial
            var touchedChannelsInJourney = cleanTouches
                .Distinct(StringComparer.OrdinalIgnoreCase)
                .ToList();

            foreach (var ch in touchedChannelsInJourney)
            {
                if (channelConvertingTouches.ContainsKey(ch))
                {
                    if (journey.Converted)
                        channelConvertingTouches[ch] += count;
                    else
                        channelNonConvertingTouches[ch] += count;
                }
            }

            if (cleanTouches.Count == 0)
            {
                string outcome = journey.Converted ? ConversionState : DropOffState;
                RecordTransition(transitionCounts, StartState, outcome, count);
                continue;
            }

            // Start -> first touchpoint
            RecordTransition(transitionCounts, StartState, cleanTouches[0], count);

            // Channel -> Channel transitions
            for (int i = 0; i < cleanTouches.Count - 1; i++)
            {
                RecordTransition(transitionCounts, cleanTouches[i], cleanTouches[i + 1], count);
            }

            // Last touchpoint -> Conversion or DropOff
            string finalOutcome = journey.Converted ? ConversionState : DropOffState;
            RecordTransition(transitionCounts, cleanTouches[^1], finalOutcome, count);
        }

        // 3. Compute baseline conversion probability via absorbing Markov chain
        double baselineConversionProb = ComputeAbsorptionProbability(
            distinctChannels,
            transitionCounts,
            channelToExclude: null);

        // 4. Compute removal effects for each channel
        var removalEffects = new Dictionary<string, double>(StringComparer.OrdinalIgnoreCase);
        foreach (var channel in distinctChannels)
        {
            double probWithoutChannel = ComputeAbsorptionProbability(
                distinctChannels,
                transitionCounts,
                channelToExclude: channel);

            double effect = 0.0;
            if (baselineConversionProb > 1e-9)
            {
                effect = Math.Max(0.0, 1.0 - (probWithoutChannel / baselineConversionProb));
            }
            removalEffects[channel] = effect;
        }

        double totalRemoval = removalEffects.Values.Sum();

        // 5. Compute Bayesian posteriors and blend with Markov weights
        List<MarkovAttributionResult> results = [];
        double totalBlendedWeight = 0.0;
        var preBlended = new List<(string Channel, double Removal, double MarkovWeight, double BayesProb, double RawBlended)>();

        foreach (var channel in distinctChannels)
        {
            double removal = removalEffects[channel];
            double markovWeight = totalRemoval > 1e-9 ? removal / totalRemoval : (1.0 / distinctChannels.Count);

            int conv = channelConvertingTouches[channel];
            int nonConv = channelNonConvertingTouches[channel];

            double postAlpha = priorAlpha + conv;
            double postBeta = priorBeta + nonConv;
            double bayesExpectedProb = postAlpha / (postAlpha + postBeta);

            double rawBlended = markovWeight * bayesExpectedProb;
            totalBlendedWeight += rawBlended;

            preBlended.Add((channel, removal, markovWeight, bayesExpectedProb, rawBlended));
        }

        foreach (var item in preBlended)
        {
            double finalWeight = totalBlendedWeight > 1e-9 ? (item.RawBlended / totalBlendedWeight) : (1.0 / distinctChannels.Count);
            double attributedConvs = totalConversions * finalWeight;
            double attributedRev = totalRevenue * finalWeight;

            results.Add(new MarkovAttributionResult(
                Channel: item.Channel,
                RemovalEffect: Math.Round(item.Removal, 6),
                MarkovAttributionWeight: Math.Round(item.MarkovWeight, 6),
                BayesianConversionProbability: Math.Round(item.BayesProb, 6),
                BlendedAttributionWeight: Math.Round(finalWeight, 6),
                AttributedConversions: Math.Round(attributedConvs, 4),
                AttributedRevenue: Math.Round(attributedRev, 2)));
        }

        return results;
    }

    /// <summary>
    /// Ranks marketing channels by marginal ROAS and assigns actionable efficiency tiers.
    /// </summary>
    public IReadOnlyList<ChannelEfficiencyRanking> RankChannelsByEfficiency(
        IReadOnlyList<(string ChannelId, string ChannelName, double CurrentSpend, HillParameters Params)> channels)
    {
        List<ChannelEfficiencyRanking> rankings = [];

        foreach (var (channelId, channelName, spend, hillParams) in channels)
        {
            double predRevenue = EvaluateHillCurve(spend, hillParams);
            double avgRoas = CalculateAverageRoas(spend, hillParams);
            double marginalRoas = CalculateMarginalRoas(spend, hillParams);
            double saturation = CalculateSaturationPercentage(spend, hillParams);

            ChannelEfficiencyTier tier;
            string recommendation;

            if (marginalRoas < 0.4)
            {
                tier = ChannelEfficiencyTier.UnprofitableKill;
                recommendation = "Marginal ROAS is sub-economic (< 0.4x). Halt expansion and reallocate budget immediately.";
            }
            else if (saturation > 85.0 || marginalRoas < 0.8)
            {
                tier = ChannelEfficiencyTier.SaturatedReduce;
                recommendation = $"Channel is highly saturated ({saturation:F1}%). Trim spend to restore marginal return efficiency.";
            }
            else if (saturation < 50.0 && marginalRoas > 2.0)
            {
                tier = ChannelEfficiencyTier.AggressiveScaleUp;
                recommendation = $"High untapped potential (Saturation {saturation:F1}%, Marginal ROAS {marginalRoas:F2}x). Aggressively increase daily budget.";
            }
            else if (saturation < 70.0 && marginalRoas > 1.2)
            {
                tier = ChannelEfficiencyTier.ScaleUp;
                recommendation = $"Healthy expansion opportunity (Marginal ROAS {marginalRoas:F2}x). Incrementally scale budget up to pacing throttles.";
            }
            else
            {
                tier = ChannelEfficiencyTier.Optimal;
                recommendation = $"Operating near optimal equilibrium (Saturation {saturation:F1}%, Marginal ROAS {marginalRoas:F2}x). Maintain spend.";
            }

            rankings.Add(new ChannelEfficiencyRanking(
                ChannelId: channelId,
                ChannelName: channelName,
                CurrentSpend: spend,
                PredictedRevenue: Math.Round(predRevenue, 2),
                AverageRoas: Math.Round(avgRoas, 4),
                MarginalRoas: Math.Round(marginalRoas, 4),
                SaturationPercentage: Math.Round(saturation, 2),
                HalfSaturationSpendK: hillParams.K,
                Tier: tier,
                Recommendation: recommendation));
        }

        return rankings
            .OrderByDescending(r => r.MarginalRoas)
            .ThenBy(r => r.SaturationPercentage)
            .ToList();
    }

    #region Markov Chain Mathematics

    private static void RecordTransition(
        Dictionary<(string From, string To), double> transitions,
        string from,
        string to,
        double count)
    {
        var key = (from, to);
        transitions[key] = transitions.GetValueOrDefault(key, 0.0) + count;
    }

    /// <summary>
    /// Solves the absorbing Markov chain for absorption into the Conversion state from the Start state.
    /// Transient states: Start + active channels (excluding channelToExclude if specified).
    /// Absorbing states: (conversion), (null).
    /// Solves (I - Q) * v = R[:, Conversion] using Gaussian elimination.
    /// </summary>
    private static double ComputeAbsorptionProbability(
        IReadOnlyList<string> channels,
        Dictionary<(string From, string To), double> transitions,
        string? channelToExclude)
    {
        // Build list of active transient states
        List<string> transientStates = [StartState];
        foreach (var ch in channels)
        {
            if (channelToExclude == null || !string.Equals(ch, channelToExclude, StringComparison.OrdinalIgnoreCase))
            {
                transientStates.Add(ch);
            }
        }

        int n = transientStates.Count;
        var stateIndex = new Dictionary<string, int>(StringComparer.OrdinalIgnoreCase);
        for (int i = 0; i < n; i++)
        {
            stateIndex[transientStates[i]] = i;
        }

        // Total outgoing transitions per state
        var outgoingTotals = new Dictionary<string, double>(StringComparer.OrdinalIgnoreCase);
        foreach (var (key, count) in transitions)
        {
            outgoingTotals[key.From] = outgoingTotals.GetValueOrDefault(key.From, 0.0) + count;
        }

        // Matrix Q: transient -> transient
        // Vector r: transient -> conversion
        double[,] A = new double[n, n]; // Will store (I - Q)
        double[] b = new double[n];     // Will store R[:, Conversion]

        for (int i = 0; i < n; i++)
        {
            string fromState = transientStates[i];
            double totalOut = outgoingTotals.GetValueOrDefault(fromState, 0.0);

            for (int j = 0; j < n; j++)
            {
                A[i, j] = (i == j) ? 1.0 : 0.0;
            }

            if (totalOut > 1e-9)
            {
                for (int j = 0; j < n; j++)
                {
                    string toState = transientStates[j];
                    double count = transitions.GetValueOrDefault((fromState, toState), 0.0);
                    double p = count / totalOut;
                    A[i, j] -= p;
                }

                double convCount = transitions.GetValueOrDefault((fromState, ConversionState), 0.0);
                b[i] = convCount / totalOut;
            }
            else
            {
                // Terminal or isolated transient state
                b[i] = 0.0;
            }
        }

        // Solve A * v = b using Gaussian elimination with partial pivoting
        double[]? solution = SolveLinearSystem(A, b, n);
        if (solution == null)
        {
            return 0.0;
        }

        // State index 0 is StartState
        return Math.Clamp(solution[0], 0.0, 1.0);
    }

    private static double[]? SolveLinearSystem(double[,] A, double[] b, int n)
    {
        double[,] m = (double[,])A.Clone();
        double[] rhs = (double[])b.Clone();

        for (int col = 0; col < n; col++)
        {
            // Partial pivoting
            int maxRow = col;
            double maxVal = Math.Abs(m[col, col]);
            for (int row = col + 1; row < n; row++)
            {
                if (Math.Abs(m[row, col]) > maxVal)
                {
                    maxVal = Math.Abs(m[row, col]);
                    maxRow = row;
                }
            }

            if (maxVal < 1e-12)
            {
                // Matrix is singular or nearly singular
                return null;
            }

            if (maxRow != col)
            {
                for (int c = col; c < n; c++)
                {
                    (m[col, c], m[maxRow, c]) = (m[maxRow, c], m[col, c]);
                }
                (rhs[col], rhs[maxRow]) = (rhs[maxRow], rhs[col]);
            }

            // Elimination
            for (int row = col + 1; row < n; row++)
            {
                double factor = m[row, col] / m[col, col];
                m[row, col] = 0.0;
                for (int c = col + 1; c < n; c++)
                {
                    m[row, c] -= factor * m[col, c];
                }
                rhs[row] -= factor * rhs[col];
            }
        }

        // Back substitution
        double[] x = new double[n];
        for (int row = n - 1; row >= 0; row--)
        {
            double sum = rhs[row];
            for (int c = row + 1; c < n; c++)
            {
                sum -= m[row, c] * x[c];
            }
            x[row] = sum / m[row, row];
        }

        return x;
    }

