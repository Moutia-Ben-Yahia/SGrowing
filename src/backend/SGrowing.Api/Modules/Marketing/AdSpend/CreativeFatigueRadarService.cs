namespace SGrowing.Api.Modules.Marketing.AdSpend;

/// <summary>
/// Daily ad set or creative level performance record used for fatigue detection.
/// </summary>
public record DailyAdPerformance(
    DateTime DateUtc,
    int Impressions,
    int Clicks,
    decimal Spend,
    int Conversions,
    decimal Revenue,
    int? UniqueReach = null)
{
    public double Ctr => Impressions > 0 ? (double)Clicks / Impressions : 0.0;
    public decimal Cpa => Conversions > 0 ? Spend / Conversions : Spend;
}

/// <summary>
/// Ordinary Least Squares (OLS) linear regression analysis of CTR over a rolling evaluation window.
/// </summary>
public record RollingWindowCtrAnalysis(
    int WindowDays,
    double SlopePerDay,
    double PercentageChange,
    double BaselineCtr,
    double RecentCtr,
    bool IsDeteriorating);

/// <summary>
/// Status of ad frequency saturation threshold evaluation.
/// </summary>
public record FrequencySaturationDiagnostic(
    double Frequency,
    double CtrDeclinePercentage,
    bool IsTriggered,
    string Message);

/// <summary>
/// Status of CPA inflection alarm evaluation (escalating CPA over 5 consecutive days).
/// </summary>
public record CpaInflectionDiagnostic(
    int ConsecutiveIncreaseDays,
    decimal InitialCpa,
    decimal CurrentCpa,
    double TotalIncreasePercentage,
    bool IsTriggered,
    string Message);

/// <summary>
/// Classification of creative fatigue severity.
/// </summary>
public enum CreativeFatigueSeverity
{
    Healthy,
    ModerateDecay,
    HighFatigue,
    CriticalCpaSpike
}

/// <summary>
/// Action priority assigned to a creative refresh recommendation.
/// </summary>
public enum TicketPriority
{
    P1_Immediate,
    P2_Within48Hours,
    P3_Scheduled,
    P4_None
}

/// <summary>
/// Actionable creative refresh recommendation ticket with tailored hook, format, and audience advice.
/// </summary>
public record CreativeRefreshTicket(
    Guid TicketId,
    string CampaignId,
    string? AdSetId,
    CreativeFatigueSeverity Severity,
    TicketPriority Priority,
    string Diagnosis,
    string RecommendedFormat,
    string HookSwapSuggestion,
    string AudienceRotationAdvice,
    DateTime CreatedAtUtc);

/// <summary>
/// Complete diagnostic report generated by the Creative Fatigue Radar.
/// </summary>
public record CreativeFatigueEvaluationResult(
    string CampaignId,
    string? AdSetId,
    DateTime EvaluationDateUtc,
    CreativeFatigueSeverity OverallSeverity,
    RollingWindowCtrAnalysis Window7Days,
    RollingWindowCtrAnalysis Window14Days,
    RollingWindowCtrAnalysis Window30Days,
    FrequencySaturationDiagnostic FrequencyStatus,
    CpaInflectionDiagnostic CpaInflectionStatus,
    CreativeRefreshTicket RefreshTicket);

/// <summary>
/// Contract for Horizon 49 Autonomous Creative Fatigue Radar &amp; CPA Inflection Service.
/// </summary>
public interface ICreativeFatigueRadarService
{
    CreativeFatigueEvaluationResult EvaluateCreativeFatigue(
        string campaignId,
        IReadOnlyList<DailyAdPerformance> history,
        string? adSetId = null,
        double? customFrequency = null);

    RollingWindowCtrAnalysis AnalyzeRollingWindowCtr(IReadOnlyList<DailyAdPerformance> history, int windowDays);
    FrequencySaturationDiagnostic EvaluateFrequencySaturation(IReadOnlyList<DailyAdPerformance> history, double? customFrequency = null);
    CpaInflectionDiagnostic EvaluateCpaInflection(IReadOnlyList<DailyAdPerformance> history);
    CreativeRefreshTicket GenerateRefreshTicket(
        string campaignId,
        string? adSetId,
        CreativeFatigueSeverity severity,
        FrequencySaturationDiagnostic frequency,
        CpaInflectionDiagnostic cpa,
        RollingWindowCtrAnalysis window7d);
}

/// <summary>
/// Implements Autonomous Creative Fatigue Radar detecting CTR decay slopes across 7, 14, and 30 day rolling windows,
/// frequency saturation thresholds (> 3.8x with > 20% CTR drop), CPA inflection alarms (> 35% hike over 5 consecutive days),
/// and synthesizes high-impact creative refresh recommendation tickets.
/// </summary>
public class CreativeFatigueRadarService : ICreativeFatigueRadarService
{
    private const double FrequencySaturationThreshold = 3.8;
    private const double FrequencyCtrDeclineThresholdPct = 20.0;
    private const int CpaInflectionRequiredConsecutiveDays = 5;
    private const double CpaInflectionPercentageThreshold = 35.0;

    /// <summary>
    /// Executes full diagnostic evaluation on historical daily ad metrics for a campaign or ad set.
    /// </summary>
    public CreativeFatigueEvaluationResult EvaluateCreativeFatigue(
        string campaignId,
        IReadOnlyList<DailyAdPerformance> history,
        string? adSetId = null,
        double? customFrequency = null)
    {
        var sortedHistory = history
            .OrderBy(h => h.DateUtc)
            .ToList();

        var win7 = AnalyzeRollingWindowCtr(sortedHistory, 7);
        var win14 = AnalyzeRollingWindowCtr(sortedHistory, 14);
        var win30 = AnalyzeRollingWindowCtr(sortedHistory, 30);

        var freqDiag = EvaluateFrequencySaturation(sortedHistory, customFrequency);
        var cpaDiag = EvaluateCpaInflection(sortedHistory);

        // Determine overall severity
        CreativeFatigueSeverity severity;
        if (cpaDiag.IsTriggered)
        {
            severity = CreativeFatigueSeverity.CriticalCpaSpike;
        }
        else if (freqDiag.IsTriggered)
        {
            severity = CreativeFatigueSeverity.HighFatigue;
        }
        else if (win7.IsDeteriorating || win7.PercentageChange < -15.0)
        {
            severity = CreativeFatigueSeverity.ModerateDecay;
        }
        else
        {
            severity = CreativeFatigueSeverity.Healthy;
        }

        var ticket = GenerateRefreshTicket(campaignId, adSetId, severity, freqDiag, cpaDiag, win7);

        return new CreativeFatigueEvaluationResult(
            CampaignId: campaignId,
            AdSetId: adSetId,
            EvaluationDateUtc: DateTime.UtcNow,
            OverallSeverity: severity,
            Window7Days: win7,
            Window14Days: win14,
            Window30Days: win30,
            FrequencyStatus: freqDiag,
            CpaInflectionStatus: cpaDiag,
            RefreshTicket: ticket);
    }

    /// <summary>
    /// Calculates OLS linear regression slope of daily CTR and percentage change over specified rolling window.
    /// </summary>
    public RollingWindowCtrAnalysis AnalyzeRollingWindowCtr(IReadOnlyList<DailyAdPerformance> history, int windowDays)
    {
        if (history.Count == 0 || windowDays <= 0)
        {
            return new RollingWindowCtrAnalysis(windowDays, 0.0, 0.0, 0.0, 0.0, false);
        }

        var windowRecords = history.TakeLast(windowDays).ToList();
        int n = windowRecords.Count;

        if (n < 2)
        {
            double singleCtr = windowRecords[0].Ctr;
            return new RollingWindowCtrAnalysis(windowDays, 0.0, 0.0, singleCtr, singleCtr, false);
        }

        double[] ctrValues = windowRecords.Select(r => r.Ctr).ToArray();

        // OLS linear regression: t = 1..n
        double tMean = (n + 1.0) / 2.0;
        double ctrMean = ctrValues.Average();

        double numerator = 0.0;
        double denominator = 0.0;

        for (int i = 0; i < n; i++)
        {
            double tDiff = (i + 1) - tMean;
            numerator += tDiff * (ctrValues[i] - ctrMean);
            denominator += tDiff * tDiff;
        }

        double slope = denominator > 1e-12 ? numerator / denominator : 0.0;

        // Baseline: average of first half (min 1, max 3) vs recent (last 1-3)
        int sampleSpan = Math.Min(3, Math.Max(1, n / 2));
        double baselineCtr = ctrValues.Take(sampleSpan).Average();
        double recentCtr = ctrValues.TakeLast(sampleSpan).Average();

        double pctChange = 0.0;
        if (baselineCtr > 1e-9)
        {
            pctChange = ((recentCtr - baselineCtr) / baselineCtr) * 100.0;
        }

        bool isDeteriorating = slope < -0.0001 && pctChange < -10.0;

        return new RollingWindowCtrAnalysis(
            WindowDays: windowDays,
            SlopePerDay: Math.Round(slope, 6),
            PercentageChange: Math.Round(pctChange, 2),
            BaselineCtr: Math.Round(baselineCtr, 6),
            RecentCtr: Math.Round(recentCtr, 6),
            IsDeteriorating: isDeteriorating);
    }

    /// <summary>
    /// Checks frequency saturation threshold: frequency &gt; 3.8x with CTR decline &gt; 20%.
    /// </summary>
    public FrequencySaturationDiagnostic EvaluateFrequencySaturation(
        IReadOnlyList<DailyAdPerformance> history,
        double? customFrequency = null)
    {
        if (history.Count == 0)
        {
            return new FrequencySaturationDiagnostic(0.0, 0.0, false, "No history available.");
        }

        double frequency;
        if (customFrequency.HasValue)
        {
            frequency = customFrequency.Value;
        }
        else
        {
            long totalImpressions = history.Sum(h => (long)h.Impressions);
            int totalReach = history.Where(h => h.UniqueReach.HasValue).Select(h => h.UniqueReach!.Value).DefaultIfEmpty(0).Max();

            if (totalReach > 0)
            {
                frequency = (double)totalImpressions / totalReach;
            }
            else
            {
                // Fallback heuristic if reach is omitted
                frequency = Math.Min(5.0, 1.0 + (history.Count * 0.15));
            }
        }

        // Evaluate CTR decline over available history
        var win7 = AnalyzeRollingWindowCtr(history, 7);
        double ctrDeclinePct = win7.PercentageChange < 0.0 ? Math.Abs(win7.PercentageChange) : 0.0;

        bool isTriggered = frequency > FrequencySaturationThreshold && ctrDeclinePct >= FrequencyCtrDeclineThresholdPct;

        string message = isTriggered
            ? $"Frequency saturation triggered! Ad frequency is {frequency:F2}x (> {FrequencySaturationThreshold}x) with a {ctrDeclinePct:F1}% CTR decline."
            : $"Ad frequency is {frequency:F2}x with {ctrDeclinePct:F1}% CTR decline (Threshold: >{FrequencySaturationThreshold}x and >{FrequencyCtrDeclineThresholdPct}% drop).";

        return new FrequencySaturationDiagnostic(
            Frequency: Math.Round(frequency, 2),
            CtrDeclinePercentage: Math.Round(ctrDeclinePct, 2),
            IsTriggered: isTriggered,
            Message: message);
    }

    /// <summary>
    /// Evaluates CPA inflection: triggers alarm when CPA increases over 5 consecutive days with &gt; 35% total hike.
    /// </summary>
    public CpaInflectionDiagnostic EvaluateCpaInflection(IReadOnlyList<DailyAdPerformance> history)
    {
        if (history.Count < CpaInflectionRequiredConsecutiveDays)
        {
            return new CpaInflectionDiagnostic(
                ConsecutiveIncreaseDays: 0,
                InitialCpa: 0m,
                CurrentCpa: 0m,
                TotalIncreasePercentage: 0.0,
                IsTriggered: false,
                Message: $"Insufficient history: {history.Count} days provided, minimum {CpaInflectionRequiredConsecutiveDays} required.");
        }

        var last5 = history.TakeLast(CpaInflectionRequiredConsecutiveDays).ToList();
        var cpas = last5.Select(d => d.Cpa).ToArray();

        int consecutiveIncreases = 0;
        for (int i = 1; i < cpas.Length; i++)
        {
            if (cpas[i] > cpas[i - 1])
            {
                consecutiveIncreases++;
            }
            else
            {
                break;
            }
        }

        decimal initialCpa = cpas[0];
        decimal currentCpa = cpas[^1];
        double totalIncreasePct = 0.0;

        if (initialCpa > 0m)
        {
            totalIncreasePct = (double)((currentCpa - initialCpa) / initialCpa) * 100.0;
        }

        bool all5Increasing = consecutiveIncreases == (CpaInflectionRequiredConsecutiveDays - 1);
        bool exceededHikeThreshold = totalIncreasePct >= CpaInflectionPercentageThreshold;
        bool isTriggered = all5Increasing && exceededHikeThreshold;

        string message;
        if (isTriggered)
        {
            message = $"CPA inflection alarm active! CPA escalated for 5 consecutive days from ${initialCpa:F2} to ${currentCpa:F2} (+{totalIncreasePct:F1}%).";
        }
        else if (all5Increasing)
        {
            message = $"CPA has risen for 5 consecutive days (+{totalIncreasePct:F1}%), but has not yet crossed the {CpaInflectionPercentageThreshold}% threshold.";
        }
        else
        {
            message = $"CPA inflection stable. Consecutive daily increase streak is {consecutiveIncreases} days.";
        }

        return new CpaInflectionDiagnostic(
            ConsecutiveIncreaseDays: consecutiveIncreases + 1,
            InitialCpa: Math.Round(initialCpa, 2),
            CurrentCpa: Math.Round(currentCpa, 2),
            TotalIncreasePercentage: Math.Round(totalIncreasePct, 2),
            IsTriggered: isTriggered,
            Message: message);
    }

    /// <summary>
    /// Formulates targeted creative refresh recommendation ticket based on detected decay patterns.
    /// </summary>
    public CreativeRefreshTicket GenerateRefreshTicket(
        string campaignId,
        string? adSetId,
        CreativeFatigueSeverity severity,
        FrequencySaturationDiagnostic frequency,
        CpaInflectionDiagnostic cpa,
        RollingWindowCtrAnalysis window7d)
    {
        TicketPriority priority;
        string diagnosis;
        string recommendedFormat;
        string hookSwap;
        string audienceRotation;

        switch (severity)
        {
            case CreativeFatigueSeverity.CriticalCpaSpike:
                priority = TicketPriority.P1_Immediate;
                diagnosis = $"Critical cost escalation: {cpa.Message} Emergency creative rotation required.";
                recommendedFormat = "Deploy 9:16 UGC short-form problem-solution video with raw unboxing and split-screen before/after visuals.";
                hookSwap = "Replace opening 0-3 second frame with high-contrast shock stat: 'Stop wasting money on X' or viral curiosity soundbite.";
                audienceRotation = "Immediately exclude 30-day website visitors and past converters. Expand seed lookalike threshold from 1% to 2.5% or test broad targeting.";
                break;

            case CreativeFatigueSeverity.HighFatigue:
                priority = TicketPriority.P2_Within48Hours;
                diagnosis = $"High audience fatigue: {frequency.Message} Saturation ceiling reached.";
                recommendedFormat = "Rotate from static 1:1 image to multi-card dynamic carousel featuring 4 distinct product benefits and customer micro-reviews.";
                hookSwap = "Swap hook to direct founder story or third-party authority testimonial ('Why dermatologists switched to...').";
                audienceRotation = "Rotate ad set audience to adjacent interest clusters; refresh custom lookalike audiences with last 90-day LTV-weighted buyers.";
                break;

            case CreativeFatigueSeverity.ModerateDecay:
                priority = TicketPriority.P3_Scheduled;
                diagnosis = $"Early creative fatigue detected: 7-day CTR trended downward by {Math.Abs(window7d.PercentageChange):F1}% (slope: {window7d.SlopePerDay:F6}).";
                recommendedFormat = "Produce 2 fresh UGC concept variations with alternative color palettes and refreshed background music.";
                hookSwap = "Test question hook ('Still dealing with X?') against demonstration hook ('Watch what happens in 10 seconds').";
                audienceRotation = "Maintain current audience but prepare fresh creative flight for next weekly deployment.";
                break;

            case CreativeFatigueSeverity.Healthy:
            default:
                priority = TicketPriority.P4_None;
                diagnosis = "Creative performance is healthy. CTR and CPA are within expected baseline variance.";
                recommendedFormat = "Maintain existing top-performing ad creative flight.";
                hookSwap = "No hook modification necessary at this time.";
                audienceRotation = "Continue standard audience scaling.";
                break;
        }

        return new CreativeRefreshTicket(
            TicketId: Guid.NewGuid(),
            CampaignId: campaignId,
            AdSetId: adSetId,
            Severity: severity,
            Priority: priority,
            Diagnosis: diagnosis,
            RecommendedFormat: recommendedFormat,
            HookSwapSuggestion: hookSwap,
            AudienceRotationAdvice: audienceRotation,
            CreatedAtUtc: DateTime.UtcNow);
    }
}
