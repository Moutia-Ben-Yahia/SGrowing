// @vitest-environment jsdom
import '@angular/compiler';
import { describe, it, expect, beforeEach } from 'vitest';
import { OnboardingWizardComponent } from './onboarding-wizard.component';

describe('OnboardingWizardComponent', () => {
  let component: OnboardingWizardComponent;

  beforeEach(() => {
    component = new OnboardingWizardComponent();
  });

  it('should initialize with 4 onboarding steps at step 1 with 0% progress', () => {
    expect(component).toBeTruthy();
    expect(component.currentStep()).toBe(1);
    expect(component.steps().length).toBe(4);
    expect(component.progressPercent()).toBe(0);
    expect(component.dnsVerified()).toBe(false);
    expect(component.pipelineLaunched()).toBe(false);
  });

  it('should verify domain DNS records and generate DKIM keys', () => {
    component.verifyDns();
    expect(component.dnsVerified()).toBe(true);

    component.autoGenerateDkim();
    expect(component.dnsVerified()).toBe(true);
  });

  it('should mark steps as complete and advance wizard step with progress update', () => {
    component.markStepComplete(1, 2);

    expect(component.steps()[0].completed).toBe(true);
    expect(component.currentStep()).toBe(2);
    expect(component.progressPercent()).toBe(25);

    component.markStepComplete(2, 3);
    expect(component.progressPercent()).toBe(50);
  });

  it('should load sample CSV leads for ingestion', () => {
    component.loadSampleCsv();

    expect(component.csvRecords().length).toBe(3);
    expect(component.csvRecords()[0].company).toBe('Maghreb Retail');
  });

  it('should launch pipeline and complete final activation step', () => {
    component.markStepComplete(1);
    component.markStepComplete(2);
    component.markStepComplete(3);
    component.launchPipeline();

    expect(component.steps()[3].completed).toBe(true);
    expect(component.pipelineLaunched()).toBe(true);
    expect(component.progressPercent()).toBe(100);
  });

  it('should reset wizard back to clean initial state on restart', () => {
    component.markStepComplete(1, 2);
    component.loadSampleCsv();
    component.launchPipeline();

    component.resetWizard();

    expect(component.currentStep()).toBe(1);
    expect(component.progressPercent()).toBe(0);
    expect(component.dnsVerified()).toBe(false);
    expect(component.pipelineLaunched()).toBe(false);
    expect(component.csvRecords().length).toBe(0);
  });
});
