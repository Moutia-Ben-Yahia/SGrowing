using System;
using System.Collections.Generic;
using FluentAssertions;
using SGrowing.Api.Modules.Content;
using Xunit;

namespace SGrowing.Tests.Unit;

public class ContentBriefGeneratorTests
{
    private readonly ContentBriefGeneratorService _service = new();

    [Fact]
    public void GenerateBrief_WithInformationalKeyword_DetectsIntentAndBuildsComprehensiveBrief()
    {
        var request = new ContentBriefRequest(
            PrimaryKeyword: "how to implement webhook signature verification",
            SecondaryKeywords: new List<string> { "hmac sha256 header", "webhook retry policies", "developer api security" },
            TargetAudience: "Backend Software Engineers"
        );

        var brief = _service.GenerateBrief(request);

        brief.Should().NotBeNull();
        brief.PrimaryKeyword.Should().Be("how to implement webhook signature verification");
        brief.SearchIntent.Should().Be("Informational");
        brief.TargetWordCountMin.Should().Be(1500);
        brief.TargetWordCountMax.Should().Be(2400);
        brief.TargetReadingGrade.Should().Be("Grade 8-10 (Clear Technical English)");
        brief.OutlineSections.Should().HaveCountGreaterThanOrEqualTo(5);
        brief.SemanticKeywords.Should().Contain(k => k.Keyword.Contains("webhook"));
        brief.CompetitorBenchmarks.Should().NotBeNull();
        brief.CompetitorBenchmarks.AverageWordCount.Should().Be(1950);
    }

    [Fact]
    public void GenerateBrief_WithCommercialKeyword_DetectsCommercialIntentAndAdjustsWordCounts()
    {
        var request = new ContentBriefRequest(
            PrimaryKeyword: "best enterprise growth platform pricing comparison",
            SecondaryKeywords: new List<string> { "growth os cost", "saas marketing software review" }
        );

        var brief = _service.GenerateBrief(request);

        brief.SearchIntent.Should().Be("Commercial");
        brief.TargetWordCountMin.Should().Be(1800);
        brief.TargetWordCountMax.Should().Be(2600);
    }

    [Fact]
    public void GenerateBrief_WithExplicitMinMaxWords_PreservesUserOverrides()
    {
        var request = new ContentBriefRequest(
            PrimaryKeyword: "quick api guide",
            MinWordCount: 500,
            MaxWordCount: 900
        );

        var brief = _service.GenerateBrief(request);

        brief.TargetWordCountMin.Should().Be(500);
        brief.TargetWordCountMax.Should().Be(900);
    }

    [Fact]
    public void GradeDraft_WithHighQualityDraft_ReturnsExcellentGradeAndAccurateMetrics()
    {
        var draftBody = """
        # The Complete Guide to Webhook Security

        Webhook signatures are essential for ensuring that HTTP callbacks received by your application originate from trusted sources. 
        In this comprehensive technical architectural breakdown, we explore how HMAC SHA256 protects endpoints from tampering and replay attacks.

        ## What is a Webhook Signature?
        A webhook signature is a cryptographic hash generated by the sender using a shared secret key and the request body payload. 
        When the receiver gets the request, it recomputes the HMAC hash and verifies that it matches the provided header.

        ## How to Implement Signature Verification
        1. Extract the timestamp and signature from request headers.
        2. Prevent replay attacks by rejecting timestamps older than 5 minutes.
        3. Compute HMAC-SHA256 over timestamp and raw payload bytes.
        4. Use constant-time comparison to avoid timing vulnerabilities.

        ## Best Practices and Recommendations
        Always rotate secret keys periodically and utilize exponential backoff for failed webhook deliveries.
        """;

        var request = new DraftGradeRequest(
            PrimaryKeyword: "webhook signatures",
            SecondaryKeywords: new List<string> { "hmac sha256", "replay attacks", "shared secret" },
            DraftTitle: "The Complete Guide to Webhook Security",
            DraftBody: draftBody
        );

        var report = _service.GradeDraft(request);

        report.Should().NotBeNull();
        report.TotalWordCount.Should().BeGreaterThan(80);
        report.FleschReadingEase.Should().BeGreaterThan(0);
        report.Grade.Should().NotBeNullOrEmpty();
        report.CoveredKeywords.Should().Contain("webhook signatures");
        report.CoveredKeywords.Should().Contain("hmac sha256");
        report.QuestionsAnswered.Should().Contain(q => q.Contains("Addresses 'what' aspects"));
        report.QuestionsAnswered.Should().Contain(q => q.Contains("Addresses 'how' aspects"));
    }

    [Fact]
    public void GradeDraft_WithThinContentAndMissingKeywords_ReturnsLowerGradeWithRecommendations()
    {
        var thinDraft = "Just a quick note about software. It is good and works well.";

        var request = new DraftGradeRequest(
            PrimaryKeyword: "autonomous marketing multi-agent swarm",
            SecondaryKeywords: new List<string> { "vector embeddings", "event streaming", "decision engine" },
            DraftTitle: "Marketing Tools",
            DraftBody: thinDraft
        );

        var report = _service.GradeDraft(request);

        report.Grade.Should().MatchRegex("^(D|F)$");
        report.MissingKeywords.Should().Contain("autonomous marketing multi-agent swarm");
        report.MissingKeywords.Should().Contain("vector embeddings");
        report.ActionableRecommendations.Should().NotBeEmpty();
    }
}
